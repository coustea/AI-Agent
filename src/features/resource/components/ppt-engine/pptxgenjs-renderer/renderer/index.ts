/**
 * PPT Renderer - Main Entry Point
 *
 * 整合 Block 渲染器和布局渲染器，实现完整的 PPT 渲染流程
 */

import pptxgenjs from 'pptxgenjs'
import { slideSize, colorPalette, spacing } from '../design-system'
import { renderSlideLayout } from '../layout-renderers'
import type { PPTDocument, PptSlide } from '../../types/ppt'

// PptxGenJS 类型
type PptxGenJS = pptxgenjs

/**
 * 创建 PptxGenJS 实例并配置
 */
export function createPresentation(): PptxGenJS {
  const pptx = new pptxgenjs()

  // 设置幻灯片尺寸（16:9 宽屏）
  pptx.defineLayout({
    name: 'Widescreen16x9',
    width: slideSize.standard.width,
    height: slideSize.standard.height,
  })
  pptx.layout = 'Widescreen16x9'

  // 设置默认属性
  pptx.author = 'AI Learning Platform'
  pptx.company = 'Personalized Learning System'
  pptx.subject = 'Teaching Material'
  pptx.title = 'PPT Generated by PptxGenJS'

  return pptx
}

/**
 * 渲染单个幻灯片
 */
export function renderSlide(
  pptx: PptxGenJS,
  pptSlide: PptSlide,
  _index?: number
): pptxgenjs.Slide {
  // 创建新幻灯片
  const slide = pptx.addSlide()

  // 设置背景色（白色）
  slide.background = { color: colorPalette.slideBackground }

  // 添加页码
  slide.slideNumber = {
    x: 13.333 - spacing.slidePadding.right - 0.5,
    y: 7.5 - spacing.slidePadding.bottom - 0.25,
    color: colorPalette.textLight,
    fontSize: 10,
    fontFace: 'Arial',
  }

  // 渲染幻灯片内容（标题、副标题、槽位 Blocks）
  renderSlideLayout(pptx, slide, pptSlide)

  // 添加演讲者备注
  if (pptSlide.speaker_notes) {
    slide.addNotes(pptSlide.speaker_notes)
  }

  return slide
}

/**
 * 渲染整个 PPT 文档
 */
export function renderPPT(pptDocument: PPTDocument): PptxGenJS {
  // 创建演示文稿实例
  const pptx = createPresentation()

  // 设置文档标题
  pptx.title = pptDocument.title

  // 渲染所有幻灯片
  const slides = pptDocument.slides || []

  slides.forEach((pptSlide, index) => {
    renderSlide(pptx, pptSlide, index)
  })

  return pptx
}

/**
 * 导出 PPTX 文件（返回 Blob）
 */
export async function exportPPTX(pptx: PptxGenJS): Promise<Blob> {
  // PptxGenJS 支持 Blob 输出
  const blob = await pptx.write({ outputType: 'blob' })
  return blob as Blob
}

/**
 * 导出 PPTX 文件（返回 ArrayBuffer）
 */
export async function exportPPTXBuffer(pptx: PptxGenJS): Promise<ArrayBuffer> {
  const buffer = await pptx.write({ outputType: 'arraybuffer' })
  return buffer as ArrayBuffer
}

/**
 * 导出 PPTX 文件（返回 Base64）
 */
export async function exportPPTXBase64(pptx: PptxGenJS): Promise<string> {
  const base64 = await pptx.write({ outputType: 'base64' })
  return base64 as string
}

/**
 * 下载 PPTX 文件
 */
export async function downloadPPTX(
  pptx: PptxGenJS,
  filename: string = 'presentation.pptx'
): Promise<void> {
  await pptx.writeFile({ fileName: filename })
}

/**
 * 从 PPTDocument JSON 渲染并导出
 */
export async function renderAndExport(
  pptDocumentJson: unknown,
  outputType: 'blob' | 'arraybuffer' | 'base64' | 'file' = 'blob',
  filename?: string
): Promise<Blob | ArrayBuffer | string | void> {
  // 解析 JSON（假设已经经过 normalizePptDocument 处理）
  const pptDocument = pptDocumentJson as PPTDocument

  // 渲染 PPT
  const pptx = renderPPT(pptDocument)

  // 根据输出类型导出
  switch (outputType) {
    case 'blob':
      return await exportPPTX(pptx)
    case 'arraybuffer':
      return await exportPPTXBuffer(pptx)
    case 'base64':
      return await exportPPTXBase64(pptx)
    case 'file':
      return await downloadPPTX(pptx, filename || `${pptDocument.title || 'presentation'}.pptx`)
    default:
      return await exportPPTX(pptx)
  }
}

