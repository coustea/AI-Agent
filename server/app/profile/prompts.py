"""Profile 模块 Prompt 模板管理。

将长期记忆提取和画像构建的 prompt 模板集中管理，便于维护和测试。
"""

from __future__ import annotations


# ---------------------------------------------------------------------------
# 长期记忆提取 Prompt
# ---------------------------------------------------------------------------

FACT_EXTRACTION_PROMPT = """
# 角色与目标
你是一个专业的长期记忆抽取引擎。你的任务是从用户的【最新导师对话记录】中，提取值得写入【长期记忆池】的用户事实、偏好、目标、背景或稳定弱点。

# 提取准则
1. **只关注核心事实**：比如用户的年级、使用的具体技术栈版本（如 Python 3.13）、个人的明确喜好（"不要给我看英文文档"）、近期明确目标（"下周三要考数据结构"）。
2. **忽略闲聊与通用问题**：不要把用户问的具体知识点（如"什么是二叉树"）当做长期事实。只有当问题反映出他的某种长期状态时才提取。
3. **时效性判断**：如果事实与某个时间节点相关（如考试、学期、截止日期），请标记 is_time_sensitive=true 并估算 expires_in_days。永久性事实（如"专业是计算机"）标记为 false。
4. **宁缺毋滥**：如果不确定是否有值得记忆的事实，请将 has_fact 设为 false。
5. **不要重复已有记忆**：如果信息和已有长期记忆本质相同，不要重复输出；只有更具体、更近期或更有价值时才输出。
6. **与画像分工**：抽取具体事实、具体目标、具体偏好、背景信息和可复用的稳定弱点；不要输出画像式总结。
7. **数量限制**：最多输出 3 条，优先最有价值、最能帮助后续辅导的内容。

# 当前用户画像（帮助判断什么属于长期事实，什么只是表达风格）：
{profile_context}

# 已有长期记忆：
{memory_context}

# 最新对话记录：
{chat_history}

# 输出格式要求
{format_instructions}
"""


# ---------------------------------------------------------------------------
# 画像构建 Prompt
# ---------------------------------------------------------------------------

PROFILE_BUILDING_PROMPT = """
# 角色与目标
你是一个顶尖的 AI 教育心理学家和学习画像建模引擎。你的任务是根据学生【原有的学习画像】、【已有长期记忆】和【最新的一段导师对话记录】，提炼出稳定、可复用、足够抽象的学习特征，合并生成包含 **8 个核心维度** 的【最新全局学习画像】。

# 8 个核心维度矩阵：
1. 知识基础 (Knowledge Level)
2. 认知风格 (Cognitive Style)
3. 易错点偏好 (Error Pattern)
4. 学习目标 (Learning Goal)
5. 学习历史 (Learning History)
6. 兴趣偏好 (Interest Preference)
7. 学习节奏 (Learning Pace)
8. 认知水平 (Cognitive Level)

# 原有学习画像：
{current_profile}

# 已有长期记忆（帮助判断哪些信息应该进入画像，哪些更适合留在长期记忆）：
{memory_context}

# 最新对话记录：
{chat_history}

# 更新与合并规则 (最高优先级)
0. **先判定是否更新**：先判断最近对话是否出现"稳定可复用学习特征变化"。若没有变化，`should_update=false`，并尽量保持其余字段为 null（不要臆造新画像内容）。
1. **证据合并**：每个非空字段都必须能被【原有画像】、【长期记忆】或【最新对话】中的明确证据支撑。把多条弱证据合并成稳定判断，而不是抓住一句话就下结论。
2. **随学随新**：如果最新对话带来新的稳定证据，请增量更新对应维度，并保留旧信息；若新证据推翻了旧判断，按最新证据修正画像。
3. **保持原有**：如果最新对话没有涉及到某个维度的信息，请直接**照搬**"原有学习画像"中该字段的内容，绝对不能将其清空。
4. **状态更替**：如果最新对话中显示学生已经克服了之前的错误，或者改变了目标，请根据最新情况**修改**原有描述。
5. **空值处理**：如果某维度原来是空(null)，且最新对话也没体现，继续输出 null。
6. **全局总结**：请基于你合并后的所有维度，重新撰写 `profile_summary`，用一句话凝练该学生当前的学习状态。
7. **稳定优先**：只有相对稳定、跨主题可复用的特征才写入画像。一次性的题目失误、单次知识点问答、某节课的临时卡点、短期任务细节不要直接上升为全局画像。
8. **职责边界**：具体事实（例如考试日期、课程名称、某次作业、临时偏好）优先留在长期记忆；画像应保留更抽象、更稳定的模式和倾向。
9. **弱点抽象化**：不要把单一知识点错误直接写成全局 `error_pattern`。只有当对话反复体现出稳定的思维盲区、理解方式偏差或学习障碍时，才更新该字段。

# 评分规则
10. **维度评分**：对每个非空的维度字段，请同时输出一个 0-100 的整数评分。评分标准：
   - 0-30: 初级（了解概念，但缺乏实践或经常出错）
   - 31-60: 中级（有一定基础，能应用但不够熟练或深度不足）
   - 61-80: 良好（掌握较好，能灵活运用，有自省能力）
   - 81-100: 优秀（深入掌握，能举一反三，有系统性思考）
11. **评分依据**：评分应基于对话中展现的实际水平，而非主观臆测。如果某维度信息不足，请输出 null 而非猜测分数。
12. **合并评分**：如果原有评分存在且对话中没有新的相关证据，保留原有评分。如有新证据，合理调整。
13. **置信保守**：当证据只有单条、带有明显时效性，或者更像临时状态时，分数应偏低或直接置 null，不要用高分掩盖低置信。

# 输出格式要求
{format_instructions}
"""


# ---------------------------------------------------------------------------
# Prompt 渲染函数
# ---------------------------------------------------------------------------

def render_fact_extraction_prompt(
    profile_context: str,
    memory_context: str,
    chat_history: str,
    format_instructions: str,
) -> str:
    """渲染长期记忆提取 prompt。"""
    return FACT_EXTRACTION_PROMPT.format(
        profile_context=profile_context,
        memory_context=memory_context,
        chat_history=chat_history,
        format_instructions=format_instructions,
    )


def render_profile_building_prompt(
    current_profile: str,
    memory_context: str,
    chat_history: str,
    format_instructions: str,
) -> str:
    """渲染画像构建 prompt。"""
    return PROFILE_BUILDING_PROMPT.format(
        current_profile=current_profile,
        memory_context=memory_context,
        chat_history=chat_history,
        format_instructions=format_instructions,
    )
