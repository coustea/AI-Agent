def normalize_school_name(name: str) -> str:
    """标准化学校名称，处理括号和空格。"""
    name = name.strip()
    name = name.replace("（", "(").replace("）", ")")
    return name


def get_school_tier(name: str, benke_level: str) -> str:
    """根据学校名称和办学层次确定院校层次。

    Returns:
        "985" | "211" | "双一流" | "普通本科" | "专科"
    """
    normalized = normalize_school_name(name)

    # 专科院校直接返回专科
    if benke_level == "专科":
        return "专科"

    # 精确匹配检查（避免"电子科技大学"匹配到"杭州电子科技大学"）
    # 检查是否为985
    if normalized in SCHOOLS_985:
        return "985"

    # 检查是否为211
    if normalized in SCHOOLS_211:
        return "211"

    # 检查是否为双一流
    if normalized in SCHOOLS_DOUBLE_FIRST_CLASS:
        return "双一流"

    # 其他本科院校
    return "普通本科"


async def read_school_excel(path: Path) -> list[tuple[str, str, str]]:
    """读取高校名单 Excel，返回 (学校名称, 办学层次, 院校层次) 列表。"""
    if not path.exists():
        logger.warning("[SchoolImport] Excel 文件不存在: %s", path)
        return []

    for skiprows in range(0, 6):
        try:
            df = pd.read_excel(path, skiprows=skiprows)
            df.columns = [str(col).strip() for col in df.columns]

            if "学校名称" in df.columns and "办学层次" in df.columns:
                result = df[["学校名称", "办学层次"]].copy()
                result = result.dropna(subset=["学校名称"])
                result["学校名称"] = result["学校名称"].astype(str).str.strip()
                result["办学层次"] = result["办学层次"].astype(str).str.strip()

                # 添加院校层次
                result["院校层次"] = result.apply(
                    lambda row: get_school_tier(row["学校名称"], row["办学层次"]),
                    axis=1,
                )

                return [
                    (row["学校名称"], row["办学层次"], row["院校层次"])
                    for _, row in result.iterrows()
                ]

        except Exception:
            continue

    logger.error("[SchoolImport] 没有找到字段：学校名称、办学层次")
    return []


async def import_schools(session: AsyncSession) -> int:
    """导入学校数据到数据库。

    Args:
        session: 数据库会话

    Returns:
        新增学校数量
    """
    schools_data = await read_school_excel(SCHOOL_EXCEL_PATH)
    if not schools_data:
        logger.info("[SchoolImport] 无学校数据需要导入")
        return 0

    count = 0
    for name, level, tier in schools_data:
        # 检查是否已存在
        stmt = select(School).where(School.name == name)
        existing = (await session.exec(stmt)).first()
        if existing:
            continue

        school = School(name=name, level=level, tier=tier)
        session.add(school)
        count += 1

    await session.commit()
    logger.info("[SchoolImport] 导入完成，新增 %d 所学校", count)
    return count
